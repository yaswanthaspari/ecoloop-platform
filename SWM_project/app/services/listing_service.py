"""
EcoLoop Listing Service
========================
Centralises listing create/update logic, image handling,
status-change recording, and validation — keeping route functions thin.
"""
from __future__ import annotations

import os
import uuid
import logging
from datetime import datetime, timezone
from typing import Optional
from werkzeug.utils import secure_filename
from flask import current_app
from PIL import Image as PILImage

from app import db
from app.models.listing import Listing
from app.models.listing_status_history import ListingStatusHistory
from app.models.image_assessment import ImageAssessment
from app.models.recommendation import Recommendation

logger = logging.getLogger(__name__)

ALLOWED_EXTENSIONS = {"jpg", "jpeg", "png", "webp", "gif"}


def allowed_file(filename: str) -> bool:
    return (
        "." in filename
        and filename.rsplit(".", 1)[1].lower() in ALLOWED_EXTENSIONS
    )


def save_upload(file_storage) -> Optional[str]:
    """
    Validate and save an uploaded image file.
    Returns a relative path (relative to UPLOAD_FOLDER) or None on failure.

    Security (SEC-04, VAL-03):
      - Extension allow-list enforced.
      - File content verified with Pillow.
      - Filename generated by UUID — never trusts user-supplied name.
    """
    if not file_storage or file_storage.filename == "":
        return None

    original = secure_filename(file_storage.filename)
    if not allowed_file(original):
        raise ValueError(f"File type not allowed. Accepted types: {ALLOWED_EXTENSIONS}")

    ext = original.rsplit(".", 1)[1].lower()
    safe_name = f"{uuid.uuid4().hex}.{ext}"
    upload_dir = current_app.config["UPLOAD_FOLDER"]
    os.makedirs(upload_dir, exist_ok=True)
    dest = os.path.join(upload_dir, safe_name)

    file_storage.save(dest)

    # Verify it is actually an image
    try:
        with PILImage.open(dest) as img:
            img.verify()
    except Exception:
        os.remove(dest)
        raise ValueError("Uploaded file does not appear to be a valid image.")

    return safe_name   # relative path / storage key


def change_status(
    listing: Listing,
    new_status: str,
    changed_by_id: int,
    note: str = "",
) -> None:
    """Record a status change and update the listing (FLOW-04, FR-12)."""
    if new_status not in Listing.VALID_STATUSES:
        raise ValueError(f"Invalid status: {new_status}")

    history = ListingStatusHistory(
        listing_id=listing.id,
        changed_by=changed_by_id,
        old_status=listing.status,
        new_status=new_status,
        note=note,
        changed_at=datetime.now(timezone.utc),
    )
    listing.status = new_status
    listing.updated_at = datetime.now(timezone.utc)
    db.session.add(history)


def save_assessment(listing_id: int, result, detected_components: list = None, diagnostic_answers: dict = None) -> ImageAssessment:
    """Upsert an ImageAssessment for a listing with detected components and diagnostic findings."""
    import json
    existing = ImageAssessment.query.filter_by(listing_id=listing_id).first()
    if existing:
        db.session.delete(existing)
        db.session.flush()

    comp_data = detected_components if detected_components is not None else getattr(result, "detected_components", [])
    ans_data = diagnostic_answers if diagnostic_answers is not None else getattr(result, "diagnostic_answers", {})

    assessment = ImageAssessment(
        listing_id=listing_id,
        predicted_category=result.predicted_category,
        confidence=result.confidence,
        model_version=result.model_version,
        inference_status=result.inference_status,
        detected_components=json.dumps(comp_data) if comp_data else None,
        diagnostic_answers=json.dumps(ans_data) if ans_data else None,
    )
    db.session.add(assessment)
    return assessment


def save_recommendation(listing_id: int, result, eco_source_ids: list = None) -> Recommendation:
    """Upsert a Recommendation for a listing."""
    import json

    existing = Recommendation.query.filter_by(listing_id=listing_id).first()
    if existing:
        db.session.delete(existing)
        db.session.flush()

    rec = Recommendation(
        listing_id=listing_id,
        route=result.route,
        suitability_score=result.suitability_score,
        reason_codes=json.dumps(result.reason_codes),
        explanation=result.explanation,
        safety_flag=result.safety_flag,
        manual_review_flag=result.manual_review_flag,
        missing_info=json.dumps(result.missing_info),
    )
    db.session.add(rec)
    return rec
